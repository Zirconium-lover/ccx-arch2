"""Centre-cracked plate M(T) with a UC6 plane along the ligament.

Half model in x (symmetry u_x = 0 at x = 0), both halves in y with the
interface at y = 0: the crack faces 0 < x < a are free, the ligament
a < x < W carries UC6 triangles.  One C3D8 layer of thickness t, z free
(plane stress).  Mesh: nx uniform columns over W; in y each half has ny rows
graded geometrically so that the first row is as tall as a column is wide.
Loading: u_y = +U on the top edge, -U... no: bottom edge held in y, top edge
displaced, one node pinned in z.  Everything scales with W, so a size sweep
is one call with a different W.
"""
import math


def grading(h0, hlen, n):
    """ratio r with h0 (r^n - 1)/(r - 1) = hlen"""
    if abs(h0 * n - hlen) < 1e-12:
        return 1.0
    lo, hi = 1.0 + 1e-9, 2.0
    for _ in range(200):
        r = 0.5 * (lo + hi)
        s = h0 * (r ** n - 1) / (r - 1)
        lo, hi = (r, hi) if s < hlen else (lo, r)
    return 0.5 * (lo + hi)


def deck(W, a_over_w=0.3, h_over_w=1.5, nx=60, ny=24, t=None, e=1.0e5, nu=0.3,
         kn=1.0e8, tn0=100.0, gc=1.0, gmin=1e-6, uend=None, dt=0.01):
    t = t or W / nx
    hx = W / nx
    H = h_over_w * W
    r = grading(hx, H, ny)
    ys = [0.0]
    for j in range(ny):
        ys.append(ys[-1] + hx * r ** j)
    ys[-1] = H
    nid = {}
    co = {}
    n = 0
    for half in (-1, 1):                # bottom (-1) and top (+1) blocks have their own nodes at y=0
        for j in range(ny + 1):
            for i in range(nx + 1):
                for k in (0, 1):
                    n += 1
                    nid[(half, j, i, k)] = n
                    co[n] = (i * hx, half * ys[j], k * t)
    L = ["** M(T) plate with a UC6 ligament - generated by test/mech/size_effect/plate.py",
         "**   W=%g a/W=%g H/W=%g nx=%d ny=%d t=%g  Kn=%g Tn0=%g Gc=%g" % (W, a_over_w, h_over_w, nx, ny, t, kn, tn0, gc),
         "*NODE, NSET=NALL"]
    L += ["%d, %.12g, %.12g, %.12g" % ((m,) + co[m]) for m in sorted(co)]
    L.append("*ELEMENT, TYPE=C3D8, ELSET=EBULK")
    eid = 0
    for half in (-1, 1):
        for j in range(ny):
            for i in range(nx):
                q = lambda jj, ii, k: nid[(half, jj, ii, k)]
                c = [q(j, i, 0), q(j, i + 1, 0), q(j + 1, i + 1, 0), q(j + 1, i, 0),
                     q(j, i, 1), q(j, i + 1, 1), q(j + 1, i + 1, 1), q(j + 1, i, 1)]
                if half < 0:            # keep a positive Jacobian below y = 0
                    c = [c[3], c[2], c[1], c[0], c[7], c[6], c[5], c[4]]
                eid += 1
                L.append("%d, " % eid + ", ".join(map(str, c)))
    L += ["*USER ELEMENT, TYPE=UC6, NODES=6, INTEGRATION POINTS=3, MAXDOF=3",
          "*ELEMENT, TYPE=UC6, ELSET=ECOH"]
    ia = int(round(a_over_w * nx))
    for i in range(ia, nx):
        b = lambda ii, k: nid[(-1, 0, ii, k)]
        tp = lambda ii, k: nid[(1, 0, ii, k)]
        # normal (x2-x1)x(x3-x1) must be +y: in the x-z plane, (dx,0,0)x(0,0,dz) = (0,-dx dz,0),
        # so order the bottom face's triangles with z first
        for tri in (((i, 0), (i, 1), (i + 1, 1)), ((i, 0), (i + 1, 1), (i + 1, 0))):
            eid += 1
            L.append("%d, " % eid + ", ".join(str(b(*p)) for p in tri) + ", "
                     + ", ".join(str(tp(*p)) for p in tri))
    L += ["*NSET, NSET=NSYM"] + [str(nid[(h, j, 0, k)]) for h in (-1, 1) for j in range(ny + 1) for k in (0, 1)]
    L += ["*NSET, NSET=NBOT"] + [str(nid[(-1, ny, i, k)]) for i in range(nx + 1) for k in (0, 1)]
    L += ["*NSET, NSET=NTOP"] + [str(nid[(1, ny, i, k)]) for i in range(nx + 1) for k in (0, 1)]
    L += ["*MATERIAL, NAME=EL", "*ELASTIC", "%g, %g" % (e, nu),
          "*MATERIAL, NAME=COH", "*ELASTIC", "%g, 0." % e, "*DEPVAR", "4",
          "*SOLID SECTION, ELSET=EBULK, MATERIAL=EL",
          "*USER SECTION, ELSET=ECOH, MATERIAL=COH, CONSTANTS=6",
          "%.12g, %.12g, %.12g, %.12g, %.12g, 0." % (kn, tn0, tn0, gc, gmin),
          "*BOUNDARY", "NSYM, 1, 1, 0.", "NBOT, 2, 2, 0.", "%d, 3, 3, 0." % nid[(-1, ny, nx, 0)],
          "%d, 1, 1, 0." % nid[(-1, ny, nx, 0)] if False else "**",
          "*STEP, INC=100000, NLGEOM", "*STATIC", "%.12g, 1., 1e-9, %.12g" % (dt, dt),
          "*BOUNDARY", "NTOP, 2, 2, %.12g" % uend,
          "*NODE PRINT, NSET=NTOP, TOTALS=ONLY", "RF", "*END STEP"]
    return "\n".join(L) + "\n"

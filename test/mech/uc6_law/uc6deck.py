"""One UC6 triangle with every node prescribed: the law seen through the solver.

Minus nodes 1,2,3 at (0,0,0), (0,a,0), (0,0,a) are held; the paired plus
nodes 4,5,6 get the jump J(t), piecewise linear in step time through one
*AMPLITUDE per component.  Normal (x2-x1)x(x3-x1) = +x, shear-1 = edge1 = +y,
shear-2 = n x s1 = +z, so the global jump IS the local separation
(dn, ds1, ds2) and the reaction on the plus nodes is area * traction.  A
free, unloaded C3D4 elsewhere gives the solver an unknown to solve for.

With rot=(theta, J0) the step instead holds the jump J0 in the reference
frame and turns the whole facet - both faces - rigidly by theta about z
through the origin, by prescribing the final rigid displacement R x - x
of every node with a linear ramp.  The ramp is a chord, not an arc, but
both faces follow the same chord, so the jump stays R(lam) J0 with |R(lam)|<=1
- the separation never grows past |J0| on the way.
"""
import math


def deck(path, props, dt, a=1.0, rot=None, tend=None):
    kn, tn0, ts0, gc, gmin, mu = props
    co = {1: (0, 0, 0), 2: (0, a, 0), 3: (0, 0, a)}
    for i in (1, 2, 3):
        co[i + 3] = co[i]
    co.update({11: (5, 0, 0), 12: (6, 0, 0), 13: (5, 1, 0), 14: (5, 0, 1)})
    L = ["** one UC6 facet, every node prescribed - generated by test/mech/uc6_law",
         "*NODE, NSET=NALL"]
    L += ["%d, %.12g, %.12g, %.12g" % ((n,) + tuple(co[n])) for n in sorted(co)]
    L += ["*USER ELEMENT, TYPE=UC6, NODES=6, INTEGRATION POINTS=3, MAXDOF=3",
          "*ELEMENT, TYPE=UC6, ELSET=ECOH", "1, 1, 2, 3, 4, 5, 6",
          "*ELEMENT, TYPE=C3D4, ELSET=EDUM", "2, 11, 12, 13, 14",
          "*NSET, NSET=NMINUS", "1, 2, 3", "*NSET, NSET=NPLUS", "4, 5, 6",
          "*MATERIAL, NAME=COH", "*ELASTIC", "1000., 0.", "*DEPVAR", "4",
          "*MATERIAL, NAME=EL", "*ELASTIC", "1000., 0.",
          "*SOLID SECTION, ELSET=EDUM, MATERIAL=EL",
          "*USER SECTION, ELSET=ECOH, MATERIAL=COH, CONSTANTS=6",
          "%.12g, %.12g, %.12g, %.12g, %.12g, %.12g" % (float(kn), float(tn0), float(ts0),
                                      float(gc), float(gmin), float(mu)),
          "*BOUNDARY", "11, 1, 3, 0.", "12, 2, 3, 0.", "13, 3, 3, 0."]
    out = ["*NODE PRINT, NSET=NPLUS, TOTALS=ONLY", "RF",
           "*EL PRINT, ELSET=ECOH", "S, SDV"]
    if rot is None:
        tend = path[-1][0]
        for c in range(3):
            L.append("*AMPLITUDE, NAME=J%d" % (c + 1))
            L += ["%.12g, %.12g" % (t, j[c]) for t, j in path]
        L += ["*BOUNDARY", "NMINUS, 1, 3, 0.",
              "*STEP, INC=100000, NLGEOM", "*STATIC, DIRECT",
              "%.12g, %.12g" % (dt, tend)]
        for c in range(3):
            L += ["*BOUNDARY, AMPLITUDE=J%d" % (c + 1), "NPLUS, %d, %d, 1." % (c + 1, c + 1)]
        L += out + ["*END STEP"]
    else:
        theta, j0 = rot
        L += ["*BOUNDARY", "NMINUS, 1, 3, 0.", "*STEP, INC=100000, NLGEOM",
              "*STATIC, DIRECT", "%.12g, 1." % dt, "*BOUNDARY"]
        L += ["%d, %d, %d, %.12g" % (n, c + 1, c + 1, j0[c]) for n in (4, 5, 6) for c in range(3)]
        L += out + ["*END STEP"]
        cs, sn = math.cos(theta), math.sin(theta)
        L += ["*STEP, INC=100000, NLGEOM", "*STATIC, DIRECT", "%.12g, 1." % dt, "*BOUNDARY"]
        for n in (1, 2, 3, 4, 5, 6):
            x = list(co[n])
            if n > 3:
                x = [x[i] + j0[i] for i in range(3)]
            rx = (cs * x[0] - sn * x[1], sn * x[0] + cs * x[1], x[2])
            for c in range(3):
                L.append("%d, %d, %d, %.12g" % (n, c + 1, c + 1, rx[c] - co[n][c]))
        L += out + ["*END STEP"]
    return "\n".join(L) + "\n"

"""Librarian benchmark B1 as a deck: a C3D8 bar, one element across, one weak element.

library notes/nonlocal-benchmarks.md sec. 1: local perfect plasticity, damage
driven by the nonlocal plastic-strain increment, initiation immediate
(eps_f -> 0), uniaxial stress (lateral faces free, nu = 0).  The bar is
statically determinate, so the answer is exact:

    D(x) = (a/u_f) phi(x),  sigma = sigma_y (1 - a/u_f),
    Delta = a + sigma * int dx / (E (1 - D(x)))

and on a mesh h the crack element reaches D = 1 at a = u_f l_d,h / l_d, so
W_crack / G_f = l_d,h / l_d (tabulated there per backend and h/ell).
"""


def deck(nx, length=10.0, iweak=None, e=1.0e5, sy=100.0, sy_bulk=102.0, uf=0.1,
         eps0=1.0e-6, ell=0.5, uend=0.15, dt=0.005, edge=False):
    h = length / nx
    if iweak is None:
        iweak = 0 if edge else nx // 2
    nid = lambda i, j, k: 1 + i * 4 + j * 2 + k
    L = ["** librarian benchmark B1, generated by test/mech/nl_benchmark/bar1d.py",
         "*NODE, NSET=NALL"]
    for i in range(nx + 1):
        for j in (0, 1):
            for k in (0, 1):
                L.append("%d, %.12g, %d, %d" % (nid(i, j, k), i * h, j, k))
    bulk, weak = [], []
    for i in range(nx):
        c = [nid(i, 0, 0), nid(i + 1, 0, 0), nid(i + 1, 1, 0), nid(i, 1, 0),
             nid(i, 0, 1), nid(i + 1, 0, 1), nid(i + 1, 1, 1), nid(i, 1, 1)]
        (weak if i == iweak else bulk).append("%d, " % (i + 1) + ", ".join(map(str, c)))
    L += ["*ELEMENT, TYPE=C3D8, ELSET=EBULK"] + bulk
    L += ["*ELEMENT, TYPE=C3D8, ELSET=EWEAK"] + weak
    L += ["*NSET, NSET=NLEFT"] + ["%d" % nid(0, j, k) for j in (0, 1) for k in (0, 1)]
    L += ["*NSET, NSET=NRIGHT"] + ["%d" % nid(nx, j, k) for j in (0, 1) for k in (0, 1)]
    for name, s in (("BULK", sy_bulk), ("WEAK", sy)):
        L += ["*MATERIAL, NAME=%s" % name, "*ELASTIC", "%g, 0." % e, "*PLASTIC", "%g, 0." % s,
              "*DAMAGE INITIATION, CRITERION=RICETRACEY, EVOLUTION=DISPLACEMENT, NONLOCAL=%r" % ell,
              "%g, 1.0, %g, 0." % (eps0, uf)]
    L += ["*SOLID SECTION, ELSET=EBULK, MATERIAL=BULK", "*SOLID SECTION, ELSET=EWEAK, MATERIAL=WEAK",
          # uniaxial: x held on the left face, the rigid modes by three
          # single dofs at the left end; lateral faces free (nu = 0 anyway)
          "*BOUNDARY", "NLEFT, 1, 1, 0.", "%d, 2, 3, 0." % nid(0, 0, 0), "%d, 3, 3, 0." % nid(0, 1, 0),
          "%d, 2, 2, 0." % nid(0, 0, 1),
          "*STEP, INC=100000, NLGEOM", "*STATIC", "%r, 1., 1e-9, %r" % (dt, dt),
          "*BOUNDARY", "NRIGHT, 1, 1, %r" % uend,
          "*NODE PRINT, NSET=NRIGHT, TOTALS=ONLY", "RF",
          "*EL PRINT, ELSET=EWEAK", "PEEQ", "*END STEP"]
    return "\n".join(L) + "\n"
